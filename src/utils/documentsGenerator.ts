function getStackSnapshot(plan: ArchitectPlan): StackSnapshot {
  const decisions = plan.decisions || {}
  const techStack = plan.techStack || {}
  const projectText = getPlanNarrativeText(plan)

  return {
    platform: firstNonEmpty(decisions.platform as string, inferPlatformFromText(projectText)),
    frontend: firstNonEmpty(decisions.frontend as string, techStack.framework, inferFrontendFromText(projectText)),
    backend: firstNonEmpty(decisions.backend as string, techStack.backend, inferBackendFromText(projectText)),
    database: firstNonEmpty(decisions.database as string, techStack.database, inferDatabaseFromText(projectText)),
    hosting: firstNonEmpty(decisions.hosting as string, techStack.hosting, inferHostingFromText(projectText)),
    styling: firstNonEmpty(decisions.styling as string, techStack.styling),
    animations: firstNonEmpty(techStack.animations, inferAnimationApproachFromText(projectText)),
    libraries: uniqueValues([...(techStack.key_libraries || []), ...inferLibrariesFromText(projectText)]),
    auth: normalizeStringArray(decisions.auth),
  }
}

