// ─── Helpers ────────────────────────────────────────────────────────────────

/** Check whether the plan has the rich v2 docs structure */
function hasRichDocs(plan: ArchitectPlan): boolean {
  return !!plan.docs && (!!plan.docs.prd || !!plan.docs.architecture || !!plan.docs.roadmap)
}

/** Get PRD data from whichever shape is available */
function getPRD(plan: ArchitectPlan): RichPRD & { techRationale?: string; designNotes?: string; sections?: string[] } {
  if (plan.docs?.prd) return plan.docs.prd as RichPRD & { techRationale?: string; designNotes?: string; sections?: string[] }
  return plan.prd || {}
}

// ─── Rich Document Generators (v2 — Frostline-style) ────────────────────────

function generateRichPRD(plan: ArchitectPlan): string {
  const prd = plan.docs!.prd || {}
  const stack = plan.techStack

  const sections: string[] = []
  sections.push(`# ${plan.name} — Product Requirements`)
  sections.push('')

  // Overview
  sections.push('## 1. Overview')
  sections.push(prd.overview || plan.description || 'No description provided.')
  sections.push('')

  // Target Users
  sections.push('## 2. Target Users')
  sections.push(prd.targetUsers || 'Define the primary audience, use cases, and user constraints.')
  sections.push('')

  // Tech Stack
  if (stack) {
    sections.push('## 3. Technology Stack')
    if (stack.framework) sections.push(`- **Framework**: ${stack.framework}`)
    if (stack.styling) sections.push(`- **Styling**: ${stack.styling}`)
    if (stack.animations) sections.push(`- **Animations**: ${stack.animations}`)
    if (stack.backend) sections.push(`- **Backend**: ${stack.backend}`)
    if (stack.database) sections.push(`- **Database**: ${stack.database}`)
    if (stack.hosting) sections.push(`- **Hosting**: ${stack.hosting}`)
    if (stack.key_libraries?.length) sections.push(`- **Key Libraries**: ${stack.key_libraries.join(', ')}`)
    sections.push('')
  }

  // Core Features
  sections.push(`## ${stack ? '4' : '3'}. Core Features`)
  if (prd.coreFeatures?.length) {
    for (const feature of prd.coreFeatures) {
      sections.push(`- ${feature}`)
    }
  } else {
    sections.push('To be defined.')
  }
  sections.push('')

  // User Flows
  if (prd.userFlows?.length) {
    sections.push('## 5. User Flows')
    for (let i = 0; i < prd.userFlows.length; i++) {
      sections.push(`${i + 1}. ${prd.userFlows[i]}`)
    }
    sections.push('')
  }

  // MVP Scope
  sections.push('## 6. MVP Scope')
  if (prd.mvpScope?.length) {
    for (const item of prd.mvpScope) {
      sections.push(`- [ ] ${item}`)
    }
  } else {
    sections.push('To be defined.')
  }
  sections.push('')

  // Content Structure
  if (prd.contentStructure) {
    sections.push('## 7. Content Structure')
    sections.push(prd.contentStructure)
    sections.push('')
  }

  // Future Considerations
  if (prd.futureConsiderations?.length) {
    sections.push('## 8. Future Considerations')
    for (const item of prd.futureConsiderations) {
      sections.push(`- ${item}`)
    }
    sections.push('')
  }

  sections.push('---')
  sections.push('*Generated by Construct Architect*')
  return sections.join('\n')
}

function generateRichArchitecture(plan: ArchitectPlan): string {
  const arch = plan.docs!.architecture || {}
  const sections: string[] = []

  sections.push(`# ${plan.name} — Technical Architecture`)
  sections.push('')

  sections.push('## 1. Overview')
  sections.push(arch.overview || `Technical architecture for ${plan.name}.`)
  sections.push('')

  if (arch.systemDiagram) {
    sections.push('## 2. System Diagram')
    sections.push('```')
    sections.push(arch.systemDiagram)
    sections.push('```')
    sections.push('')
  }

  if (arch.stateManagement) {
    sections.push('## 3. State Management')
    sections.push(arch.stateManagement)
    sections.push('')
  }

  if (arch.dataFlow) {
    sections.push('## 4. Data Flow')
    sections.push(arch.dataFlow)
    sections.push('')
  }

  if (arch.apiDesign) {
    sections.push('## 5. API Design')
    sections.push(arch.apiDesign)
    sections.push('')
  }

  if (arch.constraints?.length) {
    sections.push('## 6. Constraints')
    for (const c of arch.constraints) {
      sections.push(`- ${c}`)
    }
    sections.push('')
  }

  if (arch.performanceTargets) {
    sections.push('## 7. Performance Targets')
    const pt = arch.performanceTargets
    if (pt.initialLoad) sections.push(`- **Initial Load**: ${pt.initialLoad}`)
    if (pt.interaction) sections.push(`- **Interaction**: ${pt.interaction}`)
    if (pt.build) sections.push(`- **Build**: ${pt.build}`)
    sections.push('')
  }

  if (arch.techRationale) {
    sections.push('## 8. Technical Rationale')
    sections.push(arch.techRationale)
    sections.push('')
  }

  sections.push('---')
  sections.push('*Generated by Construct Architect*')
  return sections.join('\n')
}

function generateRichDataModels(plan: ArchitectPlan): string {
  const dm = plan.docs!.dataModels || {}
  const sections: string[] = []

  sections.push(`# ${plan.name} — Data Models & Schemas`)
  sections.push('')

  sections.push('## 1. Overview')
  sections.push(dm.overview || 'Data architecture for this project.')
  sections.push('')

  if (dm.entities?.length) {
    sections.push('## 2. Entities')
    sections.push('')
    for (const entity of dm.entities) {
      sections.push(`### ${entity.name}`)
      if (entity.description) sections.push(entity.description)
      sections.push('')

      if (entity.fields?.length) {
        sections.push('| Field | Type | Required | Description | Constraints |')
        sections.push('|-------|------|----------|-------------|-------------|')
        for (const f of entity.fields) {
          sections.push(`| ${f.name} | ${f.type} | ${f.required ? 'Yes' : 'No'} | ${f.description || ''} | ${f.constraints || ''} |`)
        }
        sections.push('')
      }

      if (entity.relationships?.length) {
        sections.push('**Relationships:**')
        for (const r of entity.relationships) {
          sections.push(`- ${r}`)
        }
        sections.push('')
      }
    }
  }

  if (dm.enums?.length) {
    sections.push('## 3. Enums')
    sections.push('')
    for (const e of dm.enums) {
      sections.push(`### ${e.name}`)
      if (e.description) sections.push(e.description)
      sections.push(`\nValues: \`${e.values.join('` | `')}\``)
      sections.push('')
    }
  }

  if (dm.apiContracts?.length) {
    sections.push('## 4. API Contracts')
    sections.push('')
    for (const api of dm.apiContracts) {
      sections.push(`### \`${api.endpoint}\``)
      if (api.description) sections.push(api.description)
      if (api.request) sections.push(`\n**Request:** \`${api.request}\``)
      if (api.response) sections.push(`**Response:** \`${api.response}\``)
      sections.push('')
    }
  }

  sections.push('---')
  sections.push('*Generated by Construct Architect*')
  return sections.join('\n')
}

function generateRichUISpec(plan: ArchitectPlan): string {
  const ui = plan.docs!.uiSpec || {}
  const sections: string[] = []

  sections.push(`# ${plan.name} — UI/UX Specification`)
  sections.push('')

  if (ui.designSystem) {
    sections.push('## 1. Design System')
    sections.push('')

    if (ui.designSystem.colors) {
      sections.push('### Colors')
      for (const [name, value] of Object.entries(ui.designSystem.colors)) {
        sections.push(`- **${name}**: ${value}`)
      }
      sections.push('')
    }

    if (ui.designSystem.typography) {
      sections.push('### Typography')
      for (const [name, value] of Object.entries(ui.designSystem.typography)) {
        sections.push(`- **${name}**: ${value}`)
      }
      sections.push('')
    }

    if (ui.designSystem.spacing) {
      sections.push('### Spacing')
      sections.push(ui.designSystem.spacing)
      sections.push('')
    }

    if (ui.designSystem.borderRadius) {
      sections.push('### Border Radius')
      sections.push(ui.designSystem.borderRadius)
      sections.push('')
    }

    if (ui.designSystem.shadows) {
      sections.push('### Shadows')
      sections.push(ui.designSystem.shadows)
      sections.push('')
    }
  }

  if (ui.screens?.length) {
    sections.push('## 2. Screens')
    sections.push('')
    for (const screen of ui.screens) {
      sections.push(`### ${screen.name}`)

      if (screen.layout) {
        sections.push('```')
        sections.push(screen.layout)
        sections.push('```')
      }

      if (screen.components?.length) {
        sections.push('\n**Components:**')
        for (const c of screen.components) sections.push(`- ${c}`)
      }

      if (screen.interactions?.length) {
        sections.push('\n**Interactions:**')
        for (const i of screen.interactions) sections.push(`- ${i}`)
      }

      if (screen.responsiveNotes) {
        sections.push(`\n**Responsive:** ${screen.responsiveNotes}`)
      }
      sections.push('')
    }
  }

  if (ui.animations?.length) {
    sections.push('## 3. Animations')
    sections.push('')
    sections.push('| Element | Trigger | Effect | Duration |')
    sections.push('|---------|---------|--------|----------|')
    for (const a of ui.animations) {
      sections.push(`| ${a.element} | ${a.trigger || ''} | ${a.effect || ''} | ${a.duration || ''} |`)
    }
    sections.push('')
  }

  if (ui.responsiveBreakpoints) {
    sections.push('## 4. Responsive Breakpoints')
    for (const [name, value] of Object.entries(ui.responsiveBreakpoints)) {
      sections.push(`- **${name}**: ${value}`)
    }
    sections.push('')
  }

  sections.push('---')
  sections.push('*Generated by Construct Architect*')
  return sections.join('\n')
}

function generateRichRoadmap(plan: ArchitectPlan): string {
  const rm = plan.docs!.roadmap || {}
  const sections: string[] = []

  sections.push(`# ${plan.name} — Development Roadmap`)
  sections.push('')

  if (rm.phases?.length) {
    for (const phase of rm.phases) {
      sections.push(`## ${phase.name}${phase.duration ? ` (${phase.duration})` : ''}`)
      if (phase.goal) sections.push(`\n**Goal:** ${phase.goal}`)
      sections.push('')

      if (phase.tasks?.length) {
        sections.push('### Tasks')
        for (const task of phase.tasks) {
          sections.push(`- [ ] ${task}`)
        }
        sections.push('')
      }

      if (phase.definitionOfDone?.length) {
        sections.push('### Definition of Done')
        for (const d of phase.definitionOfDone) {
          sections.push(`- [ ] ${d}`)
        }
        sections.push('')
      }
    }
  } else {
    sections.push('Roadmap phases to be defined.')
    sections.push('')
  }

  sections.push('---')
  sections.push('*Generated by Construct Architect*')
  return sections.join('\n')
}

function generateRichAIContext(plan: ArchitectPlan): string {
  const ai = plan.docs!.aiContext || {}
  const sections: string[] = []

  sections.push(`# ${plan.name} — AI Agent Context Guide`)
  sections.push('')
  sections.push('> This document tells code agents HOW to work in this project.')
  sections.push('> Patterns, conventions, and common mistakes to avoid.')
  sections.push('')

  if (ai.projectStructure) {
    sections.push('## 1. Project Structure')
    sections.push('```')
    sections.push(ai.projectStructure)
    sections.push('```')
    sections.push('')
  }

  if (ai.conventions?.length) {
    sections.push('## 2. Conventions')
    for (const c of ai.conventions) {
      sections.push(`- ${c}`)
    }
    sections.push('')
  }

  if (ai.patterns?.length) {
    sections.push('## 3. Common Patterns')
    sections.push('')
    for (const p of ai.patterns) {
      sections.push(`### ${p.name}`)
      for (const step of p.steps) {
        sections.push(`${step}`)
      }
      sections.push('')
    }
  }

  if (ai.commonMistakes?.length) {
    sections.push('## 4. Common Mistakes')
    sections.push('')
    for (const m of ai.commonMistakes) {
      sections.push(`- **Mistake:** ${m.mistake}`)
      sections.push(`  **Fix:** ${m.fix}`)
    }
    sections.push('')
  }

  if (ai.keyFiles?.length) {
    sections.push('## 5. Key Files')
    sections.push('')
    sections.push('| Path | Purpose |')
    sections.push('|------|---------|')
    for (const f of ai.keyFiles) {
      sections.push(`| \`${f.path}\` | ${f.purpose} |`)
    }
    sections.push('')
  }

  if (ai.testingStrategy) {
    sections.push('## 6. Testing Strategy')
    sections.push(ai.testingStrategy)
    sections.push('')
  }

  sections.push('---')
  sections.push('*Generated by Construct Architect*')
  return sections.join('\n')
}

