function formatStackNarrative(plan: ArchitectPlan, stack: StackSnapshot): string {
  const parts: string[] = []
  if (plan.techStack?.framework) parts.push(`**Framework:** ${plan.techStack.framework}`)
  if (plan.techStack?.backend) parts.push(`**Backend:** ${plan.techStack.backend}`)
  if (plan.techStack?.database) parts.push(`**Database:** ${plan.techStack.database}`)
  if (plan.techStack?.styling) parts.push(`**Styling:** ${plan.techStack.styling}`)
  if (plan.techStack?.animations) parts.push(`**Animations:** ${plan.techStack.animations}`)
  if (plan.techStack?.hosting) parts.push(`**Hosting:** ${plan.techStack.hosting}`)
  if (plan.techStack?.key_libraries?.length) parts.push(`**Key libraries:** ${plan.techStack.key_libraries.join(', ')}`)

  if (parts.length > 0) return parts.join('\n\n')

  const targets: string[] = []
  if (stack.frontend) targets.push(`- **Primary client**: ${stack.frontend}`)
  if (stack.backend) targets.push(`- **Backend/API**: ${stack.backend}`)
  if (stack.hosting) targets.push(`- **Deployment**: ${stack.hosting}`)
  return targets.length > 0 ? targets.join('\n') : `- **Primary goal**: ${plan.description || 'To be defined.'}`
}

function formatList(items?: string | string[], asChecklist = false): string {
  if (!items?.length) return 'To be defined.'
  const arr = Array.isArray(items) ? items : [items]
  const prefix = asChecklist ? '- [ ] ' : '- '
  return arr.map(item => `${prefix}${item}`).join('\n')
}

function firstNonEmpty(...values: Array<string | undefined>): string {
  for (const value of values) {
    if (typeof value === 'string' && value.trim()) return value.trim()
  }
  return ''
}

function getPlanNarrativeText(plan: ArchitectPlan): string {
  const prd = plan.prd || plan.docs?.prd || {}
  const decisionValues = Object.values(plan.decisions || {}).flatMap(value => normalizeStringArray(value))
  const techValues = normalizeStringArray([
    plan.techStack?.framework,
    plan.techStack?.styling,
    plan.techStack?.animations,
    plan.techStack?.backend,
    plan.techStack?.database,
    plan.techStack?.hosting,
    ...(plan.techStack?.key_libraries || []),
  ])

  return [
    plan.name,
    plan.description,
    (prd as Record<string, unknown>).overview as string,
    (prd as Record<string, unknown>).targetUsers as string,
    ...normalizeStringArray((prd as Record<string, unknown>).coreFeatures as string[]),
    ...normalizeStringArray((prd as Record<string, unknown>).mvpScope as string[]),
    ...normalizeStringArray((prd as Record<string, unknown>).futureConsiderations as string[]),
    ...decisionValues,
    ...techValues,
  ]
    .filter(Boolean)
    .join(' ')
}

function normalizeStringArray(value?: string | string[] | Array<string | undefined> | unknown): string[] {
  if (!value) return []
  const items = Array.isArray(value) ? value : [value]
  return items
    .flatMap(item => typeof item === 'string' ? [item] : [])
    .map(item => item.trim())
    .filter(Boolean)
}

function uniqueValues(items: string[]): string[] {
  return Array.from(new Set(items.map(item => item.trim()).filter(Boolean)))
}

function toKebabCase(str: string): string {
  return str
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

