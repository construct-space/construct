/**
 * Generate PRD markdown
 */
export function generatePRD(plan: ArchitectPlan): string {
  const prd = plan.prd || {}
  const stack = getStackSnapshot(plan)

  return `# ${plan.name} PRD

## Product Summary
${prd.overview || plan.description || 'No description provided.'}

## Target Users
${prd.targetUsers || 'Define the primary audience, use cases, and user constraints.'}

## Product Shape
${formatDecisionHighlights(plan, stack)}

## Core Features
${formatList(prd.coreFeatures)}

## MVP Release Definition
${formatList(prd.mvpScope, true)}

## Delivery Tracks
${formatDeliveryTracks(plan, stack)}

## Definition of Done
${formatDefinitionOfDone(plan)}

## Technical Direction
${formatStackNarrative(plan, stack)}

## Technical Rationale
${prd.techRationale || 'Capture why this stack and architecture fit the initial release.'}

## Design Direction
${prd.designNotes || 'Document visual identity, motion, typography, and layout principles.'}
${prd.sections?.length ? `\n## Primary Screens / Sections\n${prd.sections.map((s, i) => `${i + 1}. ${s}`).join('\n')}` : ''}
${prd.contentStructure ? `\n## Content Structure\n${prd.contentStructure}` : ''}

## Future Considerations
${formatList(prd.futureConsiderations)}

---
*Generated by Construct Architect*
`
}

