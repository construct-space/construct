/**
 * Documents Generator
 * Generates project documentation from Architect plan
 */
export type DocumentType = 'prd' | 'readme' | 'architecture' | 'roadmap' | 'setup'

export interface ArchitectPlan {
  name: string
  description: string
  type?: 'construct-space' | 'project'
  spaceId?: string
  spaceName?: string
  spaceScope?: 'project' | 'app' | 'both'
  spaceIcon?: string
  decisions: {
    platform?: string
    frontend?: string
    backend?: string
    database?: string
    auth?: string | string[]
    styling?: string
    hosting?: string
    [key: string]: string | string[] | undefined
  }
  techStack?: {
    framework?: string
    styling?: string
    animations?: string
    backend?: string
    database?: string
    hosting?: string
    key_libraries?: string[]
  }
  prd?: {
    overview?: string
    targetUsers?: string
    coreFeatures?: string[]
    techRationale?: string
    mvpScope?: string[]
    futureConsiderations?: string[]
    designNotes?: string
    sections?: string[]
    contentStructure?: string
  }
}

interface StackSnapshot {
  platform: string
  frontend: string
  backend: string
  database: string
  hosting: string
  styling: string
  animations: string
  libraries: string[]
  auth: string[]
}


