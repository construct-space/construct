function inferPlatformFromText(text: string): string {
  return inferNamedChoice(text, [
    [/\bflutter\b|\breact[\s-]?native\b|\bexpo\b|\bios\b|\bandroid\b|\bmobile\b/i, 'Mobile'],
    [/\btauri\b|\belectron\b|\bdesktop\b/i, 'Desktop'],
    [/\bnext(?:\.js)?\b|\bnuxt\b|\breact\b|\bvue\b|\bastro\b|\bweb\b|\bwebsite\b|\blanding page\b|\bsaas\b|\bdashboard\b/i, 'Web'],
  ])
}

function inferFrontendFromText(text: string): string {
  if (/\bflutter\b/i.test(text)) {
    return /\bgetx\b/i.test(text) ? 'Flutter (GetX)' : 'Flutter'
  }
  return inferNamedChoice(text, [
    [/\bexpo\b/i, 'Expo'],
    [/\breact[\s-]?native\b/i, 'React Native'],
    [/\bnext(?:\.js)?\b/i, 'Next.js'],
    [/\bnuxt\b/i, 'Nuxt'],
    [/\bvue\b/i, 'Vue'],
    [/\breact\b/i, 'React'],
    [/\btauri\b/i, 'Tauri'],
  ])
}

function inferBackendFromText(text: string): string {
  return inferNamedChoice(text, [
    [/\bgin\b|\bfiber\b|\becho\b|\bchi\b|\bgolang\b|\bgo backend\b|\bgo api\b|\bgo\b/i, 'Go'],
    [/\bfastapi\b/i, 'FastAPI'],
    [/\bexpress(?:\.js)?\b|\bnode(?:\.js)?\b/i, 'Node.js / Express'],
    [/\bnest(?:\.js)?\b/i, 'NestJS'],
    [/\bdjango\b/i, 'Django'],
    [/\blaravel\b/i, 'Laravel'],
    [/\brails\b/i, 'Rails'],
  ])
}

function inferDatabaseFromText(text: string): string {
  return inferNamedChoice(text, [
    [/\bsupabase\b/i, 'Supabase / PostgreSQL'],
    [/\bpostgres(?:ql)?\b/i, 'PostgreSQL'],
    [/\bsqlite\b/i, 'SQLite'],
    [/\bmysql\b/i, 'MySQL'],
    [/\bmongo(?:db)?\b/i, 'MongoDB'],
    [/\bfirebase\b/i, 'Firebase'],
  ])
}

function inferHostingFromText(text: string): string {
  return inferNamedChoice(text, [
    [/\bvercel\b/i, 'Vercel'],
    [/\bnetlify\b/i, 'Netlify'],
    [/\bfly\.io\b|\bfly io\b/i, 'Fly.io'],
    [/\brender\b/i, 'Render'],
    [/\brailway\b/i, 'Railway'],
    [/\baws\b/i, 'AWS'],
    [/\bcloudflare\b/i, 'Cloudflare'],
    [/\bfirebase\b/i, 'Firebase'],
    [/\bapp store\b|\bplay store\b/i, 'App Store / Play Store'],
  ])
}

function inferAnimationApproachFromText(text: string): string {
  return inferNamedChoice(text, [
    [/\breal[-\s]?time chat\b|\breal[-\s]?time\b|\blive updates?\b/i, 'Realtime updates and event-driven UI feedback'],
    [/\benergetic\b|\bsporty\b|\bplayful\b|\bbouncy\b/i, 'Snappy motion with spring-based transitions'],
    [/\bsubtle\b|\bminimal\b/i, 'Subtle motion and micro-interactions'],
  ])
}

function inferLibrariesFromText(text: string): string[] {
  const inferred: string[] = []
  if (/\bgetx\b/i.test(text)) inferred.push('GetX')
  if (/\briverpod\b/i.test(text)) inferred.push('Riverpod')
  if (/\bbloc\b/i.test(text)) inferred.push('flutter_bloc')
  if (/\bdio\b/i.test(text)) inferred.push('Dio')
  if (/\bsupabase\b/i.test(text)) inferred.push('Supabase')
  if (/\bfirebase\b/i.test(text)) inferred.push('Firebase')
  if (/\bmapbox\b/i.test(text)) inferred.push('Mapbox')
  if (/\bgoogle maps?\b/i.test(text)) inferred.push('Google Maps')
  if (/\breal[-\s]?time chat\b|\bwebsocket\b/i.test(text)) inferred.push('WebSocket transport')
  return inferred
}

function inferNamedChoice(text: string, patterns: Array<[RegExp, string]>): string {
  for (const [pattern, label] of patterns) {
    if (pattern.test(text)) return label
  }
  return ''
}

function getPrerequisites(plan: ArchitectPlan): string {
  const stack = getStackSnapshot(plan)
  const prereqs: string[] = []
  const frontend = `${stack.frontend} ${stack.platform}`.toLowerCase()
  const backend = stack.backend.toLowerCase()

  if (frontend.includes('node') || frontend.includes('nuxt') || frontend.includes('next') || frontend.includes('react') || frontend.includes('vue')) {
    prereqs.push('- Node.js 18+ and npm/bun')
  }
  if (frontend.includes('flutter')) {
    prereqs.push('- Flutter SDK 3.24+')
    prereqs.push('- Dart SDK (bundled with Flutter)')
  }
  if (frontend.includes('react native')) {
    prereqs.push('- Node.js 18+ and npm/yarn')
    prereqs.push('- React Native Android/iOS toolchain')
  }
  if (backend.includes('go') || backend.includes('gin')) {
    prereqs.push('- Go 1.21+')
  }
  if (backend.includes('python') || backend.includes('fastapi') || backend.includes('django')) {
    prereqs.push('- Python 3.11+')
  }
  if (stack.database.toLowerCase().includes('postgres')) {
    prereqs.push('- PostgreSQL 15+')
  }
  if (stack.database.toLowerCase().includes('mysql')) {
    prereqs.push('- MySQL 8+')
  }
  if (stack.database.toLowerCase().includes('mongo')) {
    prereqs.push('- MongoDB 6+')
  }

  return prereqs.length ? prereqs.join('\n') : '- Node.js 18+'
}

function getInstallCommand(plan: ArchitectPlan): string {
  const stack = getStackSnapshot(plan)
  const frontend = `${stack.frontend} ${stack.platform}`.toLowerCase()
  const backend = stack.backend.toLowerCase()
  const commands: string[] = []

  if (frontend.includes('flutter')) {
    commands.push('flutter pub get')
  } else if (frontend.includes('nuxt') || frontend.includes('vue')) {
    commands.push('bun install')
  } else if (frontend.includes('next') || frontend.includes('react native') || frontend.includes('react')) {
    commands.push('npm install')
  }

  if (backend.includes('go')) {
    if (commands.length) commands.push('')
    commands.push('# Backend')
    commands.push('go mod tidy')
  } else if (backend.includes('node') || backend.includes('express')) {
    if (commands.length) commands.push('')
    commands.push('# Backend')
    commands.push('npm install')
  }

  return commands.join('\n') || 'npm install'
}

function getDevCommand(plan: ArchitectPlan): string {
  const stack = getStackSnapshot(plan)
  const frontend = `${stack.frontend} ${stack.platform}`.toLowerCase()
  const backend = stack.backend.toLowerCase()
  const commands: string[] = []

  if (frontend.includes('flutter')) {
    commands.push('flutter run')
  } else if (frontend.includes('nuxt') || frontend.includes('vue')) {
    commands.push('bun run dev')
  } else if (frontend.includes('next') || frontend.includes('react native') || frontend.includes('react')) {
    commands.push('npm run dev')
  }

  if (backend.includes('go')) {
    if (commands.length) commands.push('')
    commands.push('# API')
    commands.push('go run ./cmd/api')
  } else if (backend.includes('node') || backend.includes('express')) {
    if (commands.length) commands.push('')
    commands.push('# API')
    commands.push('npm run api:dev')
  }

  return commands.join('\n') || 'npm run dev'
}

function getAuthEnvVars(auth?: string | string[]): string {
  if (!auth?.length) return '# AUTH_SECRET='
  const authArray = Array.isArray(auth) ? auth : [auth]
  const vars: string[] = []
  for (const a of authArray) {
    const lower = a.toLowerCase()
    if (lower.includes('oauth') || lower.includes('google')) vars.push('GOOGLE_CLIENT_ID=\nGOOGLE_CLIENT_SECRET=')
    if (lower.includes('github')) vars.push('GITHUB_CLIENT_ID=\nGITHUB_CLIENT_SECRET=')
    if (lower.includes('jwt') || lower.includes('email')) vars.push('JWT_SECRET=')
  }
  return vars.length ? vars.join('\n') : 'AUTH_SECRET='
}

function getDatabaseSetupCommandForStack(stack: StackSnapshot): string {
  const db = stack.database.toLowerCase()
  const backend = stack.backend.toLowerCase()
  const migrateCommand = backend.includes('go') ? 'go run ./cmd/migrate' : 'npm run db:migrate'
  if (db.includes('postgres')) return `# Create database\ncreatedb myapp_dev\n\n# Run migrations\n${migrateCommand}`
  if (db.includes('mysql')) return `# Create database\nmysql -e "CREATE DATABASE myapp_dev;"\n\n# Run migrations\n${migrateCommand}`
  if (db.includes('sqlite')) return `# SQLite will create file automatically\n${migrateCommand}`
  return '# Setup your database\nnpm run db:setup'
}

function getIDEExtensionsForStack(stack: StackSnapshot): string {
  const exts: string[] = ['- ESLint', '- Prettier']
  const frontend = stack.frontend.toLowerCase()
  const backend = stack.backend.toLowerCase()

  if (frontend.includes('flutter')) exts.push('- Dart', '- Flutter')
  if (frontend.includes('vue') || frontend.includes('nuxt')) exts.push('- Volar (Vue)')
  if (frontend.includes('react') || frontend.includes('next')) exts.push('- ES7+ React snippets')
  if (backend.includes('go')) exts.push('- Go')
  if (backend.includes('python')) exts.push('- Python', '- Pylance')

  return exts.join('\n')
}
