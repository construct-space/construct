function generateLegacyArchitecture(plan: ArchitectPlan): string {
  const decisions = plan.decisions || {}
  const prd = plan.prd || {}
  const stack = getStackSnapshot(plan)
  const frontend = firstNonEmpty(decisions.frontend as string, stack.frontend)
  const backend = firstNonEmpty(decisions.backend as string, stack.backend)
  const database = firstNonEmpty(decisions.database as string, stack.database)
  const auth = stack.auth.length > 0
    ? stack.auth
    : normalizeStringArray(decisions.auth)

  return `# Architecture

## Overview
This document outlines the technical architecture for ${plan.name}.

## Technology Choices

### Frontend: ${frontend || 'Not specified'}
### Backend: ${backend || 'Not specified'}
### Database: ${database || 'Not specified'}

### Authentication
${formatList(auth)}

## Technical Rationale
${prd.techRationale || 'The technology choices were made based on project requirements, team expertise, and scalability needs.'}

## System Diagram

\`\`\`
┌─────────────┐     ┌─────────────┐     ┌─────────────┐
│   Client    │────▶│   Server    │────▶│  Database   │
│ ${(frontend || 'Frontend').padEnd(11)}│     │ ${(backend || 'Backend').padEnd(11)}│     │ ${(database || 'DB').padEnd(11)}│
└─────────────┘     └─────────────┘     └─────────────┘
\`\`\`

---
*Generated by Construct Architect*
`
}

